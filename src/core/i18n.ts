export function getT(lang?: SupportedLang | 'auto') {
  let chosen: SupportedLang = 'en'
  if (!lang || lang === 'auto') {
    chosen = detectDeviceLanguage()
  } else {
    chosen = lang
  }
  return translations[chosen] || translations.en
}
