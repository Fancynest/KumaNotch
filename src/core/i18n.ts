export type SupportedLang = 'id' | 'en'

export function detectDeviceLanguage(): SupportedLang {
  if (typeof navigator !== 'undefined' && navigator.language) {
    if (navigator.language.toLowerCase().startsWith('id')) {
      return 'id'
    }
  }
  return 'en'
}

